// ValidateMaxConcurrentParam validates max-concurrent constraint parameters ({"max": N},
// N in 1..1024, spec P1-A-29). Missing/empty parameters return nil (not configured).
func ValidateMaxConcurrentParam(raw []byte) error {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return nil
	}
	var obj struct {
		Max int `json:"max"`
	}
	if err := json.Unmarshal(trimmed, &obj); err != nil {
		return fmt.Errorf("max-concurrent: invalid JSON: %v", err)
	}
	if obj.Max < MaxConcurrentMin || obj.Max > MaxConcurrentMax {
		return fmt.Errorf("max-concurrent: max %d: must be %d-%d", obj.Max, MaxConcurrentMin, MaxConcurrentMax)
	}
	return nil
}

// SPIFFE constants and helpers for optional SPIFFE identity integration.

const (
	// SPIFFEScheme is the URI scheme for SPIFFE identities.
	SPIFFEScheme = "spiffe"
	// SPIFFEAgentPrefix is the standard path prefix for agent workloads.
	SPIFFEAgentPrefix = "/agent/"
)

// BuildSPIFFEID constructs a SPIFFE ID from trust domain and agent name.
// Returns "spiffe://{trustDomain}/agent/{agentName}".
func BuildSPIFFEID(trustDomain, agentName string) string {
	return fmt.Sprintf("spiffe://%s/agent/%s", trustDomain, agentName)
}

// ValidateSPIFFEID checks that id matches the expected format:
// "spiffe://{trustDomain}/agent/{name}" where name is non-empty.
func ValidateSPIFFEID(id, trustDomain string) error {
	prefix := fmt.Sprintf("spiffe://%s/agent/", trustDomain)
	if !strings.HasPrefix(id, prefix) {
		return fmt.Errorf("spiffe: invalid ID %q: must start with %s", id, prefix)
	}
	name := strings.TrimPrefix(id, prefix)
	if name == "" {
		return fmt.Errorf("spiffe: invalid ID %q: agent name is empty", id)
	}
	if strings.Contains(name, "/") {
		return fmt.Errorf("spiffe: invalid ID %q: agent name must not contain /", id)
	}
	return nil
}

// ExtractSPIFFEIDFromCert extracts the SPIFFE ID from a certificate's SAN URIs.
// Returns empty string if no SPIFFE URI is found.
func ExtractSPIFFEIDFromCert(cert *x509.Certificate) string {
	if cert == nil {
		return ""
	}
	for _, uri := range cert.URIs {
		if uri.Scheme == SPIFFEScheme {
			return uri.String()
		}
	}
	return ""
}

// IsSPIFFEAgentID returns true if the agentId is in SPIFFE format.
func IsSPIFFEAgentID(agentId string) bool {
	return strings.HasPrefix(agentId, "spiffe://")
}

// ParseSPIFFEAgentName extracts the agent name from a SPIFFE agentId.
// "spiffe://varwof.com/agent/scheduler-a" → "scheduler-a"
// Returns the original id if it's not in SPIFFE format.
func ParseSPIFFEAgentName(agentId string) string {
	if !IsSPIFFEAgentID(agentId) {
		return agentId
	}
	idx := strings.LastIndex(agentId, "/")
	if idx < 0 {
		return agentId
	}
	return agentId[idx+1:]
}

// ParseSPIFFEDomain extracts the trust domain from a SPIFFE agentId.
// "spiffe://varwof.com/agent/scheduler-a" → "varwof.com"
// Returns empty string if not in SPIFFE format.
func ParseSPIFFEDomain(agentId string) string {
	if !IsSPIFFEAgentID(agentId) {
		return ""
	}
	trimmed := strings.TrimPrefix(agentId, "spiffe://")
	idx := strings.Index(trimmed, "/")
	if idx < 0 {
		return ""
	}
	return trimmed[:idx]
}

// AddSPIFFESANToCert adds a SPIFFE URI to a certificate's SAN URIs.
// Does not add if the SPIFFE ID already exists.
func AddSPIFFESANToCert(cert *x509.Certificate, spiffeID string) error {
	u, err := url.Parse(spiffeID)
	if err != nil {
		return fmt.Errorf("spiffe: invalid URI %q: %v", spiffeID, err)
	}
	if u.Scheme != SPIFFEScheme {
		return fmt.Errorf("spiffe: URI scheme must be %q, got %q", SPIFFEScheme, u.Scheme)
	}
	// Deduplicate
	for _, existing := range cert.URIs {
		if existing.String() == u.String() {
			return nil
		}
	}
	cert.URIs = append(cert.URIs, u)
	return nil
}
